// Generates src/telemetry.ts (Snapshot types) from docs/telemetry.schema.json. No dependencies.
// Usage: node hardware/thingy-bridge/web/dev/gen-types.js [--check]   (--check fails if the committed file is outdated)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SCHEMA = new URL('../../../../docs/telemetry.schema.json', import.meta.url);
const TARGET = new URL('../src/telemetry.ts', import.meta.url);

const pascal = (s) => s.replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase());
const literal = (v) => (v === null ? 'null' : JSON.stringify(v));
const PRIMITIVES = { integer: 'number', number: 'number', string: 'string', boolean: 'boolean', null: 'null' };

function typeOf(node, indent) {
  if (node.$ref) return pascal(node.$ref.split('/').pop());
  if (node.enum) return node.enum.map(literal).join(' | ');
  const types = [node.type].flat();
  return types.map((t) => (t === 'object' ? objectType(node, indent) : PRIMITIVES[t])).join(' | ');
}

function objectType(node, indent) {
  const required = new Set(node.required ?? []);
  const pad = '  '.repeat(indent + 1);
  const fields = Object.entries(node.properties ?? {})
    .map(([key, prop]) => `${pad}${key}${required.has(key) ? '' : '?'}: ${typeOf(prop, indent + 1)};`);
  return `{\n${fields.join('\n')}\n${'  '.repeat(indent)}}`;
}

export function generate(schema) {
  const defs = Object.entries(schema.$defs ?? {}).map(([name, def]) => `export type ${pascal(name)} = ${typeOf(def, 0)};`);
  const parts = Object.entries(schema.properties)
    .filter(([, prop]) => [prop.type].flat().includes('object'))
    .map(([key]) => `export type ${pascal(key)} = Snapshot['${key}'];`);
  return [
    '// Generated by dev/gen-types.js from docs/telemetry.schema.json – do not edit. Regenerate: ./project web types',
    ...defs,
    '',
    `export interface Snapshot ${objectType(schema, 0)}`,
    '',
    ...parts,
    '',
  ].join('\n');
}

if (import.meta.main) {
  const code = generate(JSON.parse(readFileSync(SCHEMA, 'utf8')));
  if (process.argv.includes('--check')) {
    if (readFileSync(TARGET, 'utf8') !== code) {
      console.error('src/telemetry.ts is outdated – run ./project web types');
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, code);
    console.log(`wrote ${fileURLToPath(TARGET)}`);
  }
}
